#!/bin/bash
cd /root/newappai
ER_DIR="app/easyreadvoice"
FILES=$(find "$ER_DIR" -name "*.tsx" -o -name "*.ts" | sort)
for f in $FILES; do
  # TEXT COLORS
  sed -i 's/text-white/text-#00ff41/g' "$f"
  sed -i 's/text-green-400/text-#00ff41/g' "$f"
  sed -i 's/text-green-300/text-#00ff41/g' "$f"
  sed -i 's/text-emerald-400/text-#00ff41/g' "$f"
  sed -i 's/text-slate-400/text-#00cc33/g' "$f"
  sed -i 's/text-slate-300/text-#00cc33/g' "$f"
  sed -i 's/text-slate-200/text-#00cc33/g' "$f"
  sed -i 's/text-slate-100/text-#00ff41/g' "$f"
  sed -i 's/text-slate-50/text-#00ff41/g' "$f"
  sed -i 's/text-gray-200/text-#00cc33/g' "$f"
  sed -i 's/text-gray-300/text-#00cc33/g' "$f"
  sed -i 's/text-gray-400/text-#00cc33/g' "$f"
  sed -i 's/text-gray-100/text-#00ff41/g' "$f"
  sed -i 's/text-gray-900/text-#00ff41/g' "$f"
  sed -i 's/text-gray-800/text-#00ff41/g' "$f"
  sed -i 's/text-gray-700/text-#00cc33/g' "$f"
  sed -i 's/text-gray-600/text-#00cc33/g' "$f"
  sed -i 's/text-gray-500/text-#00cc33/g' "$f"
  # BACKGROUNDS
  sed -i 's/bg-green-600/bg-#00ff41/g' "$f"
  sed -i 's/bg-green-500\/10/bg-#00ff41\/10/g' "$f"
  sed -i 's/bg-green-500\/20/bg-#00ff41\/20/g' "$f"
  sed -i 's/bg-green-900\/40/bg-#00ff41\/10/g' "$f"
  sed -i 's/bg-green-900\/50/bg-#00ff41\/10/g' "$f"
  sed -i 's/bg-green-100\/10/bg-#00ff41\/10/g' "$f"
  sed -i 's/bg-emerald-500\/10/bg-#00ff41\/10/g' "$f"
  sed -i 's/bg-emerald-600/bg-#00ff41/g' "$f"
  sed -i 's/bg-slate-900/bg-black/g' "$f"
  sed -i 's/bg-slate-800/bg-black/g' "$f"
  sed -i 's/bg-slate-950/bg-black/g' "$f"
  sed -i 's/bg-gray-900/bg-black/g' "$f"
  sed -i 's/bg-gray-800\/50/bg-#00ff41\/10/g' "$f"
  sed -i 's/bg-white\/5/bg-black/g' "$f"
  sed -i 's/bg-white\/10/bg-black/g' "$f"
  # BORDERS
  sed -i 's/border-green-500\/20/border-#00ff41\/20/g' "$f"
  sed -i 's/border-green-400\/30/border-#00ff41\/30/g' "$f"
  sed -i 's/border-green-400\/50/border-#00ff41\/50/g' "$f"
  sed -i 's/border-green-400/border-#00ff41/g' "$f"
  sed -i 's/border-green-500\/30/border-#00ff41\/30/g' "$f"
  sed -i 's/border-white\/10/border-#00ff41\/20/g' "$f"
  sed -i 's/border-white\/20/border-#00ff41\/30/g' "$f"
  sed -i 's/border-white\/5/border-#00ff41\/10/g' "$f"
  sed -i 's/border-slate-700\/50/border-#00ff41\/20/g' "$f"
  sed -i 's/border-gray-700\/50/border-#00ff41\/20/g' "$f"
  sed -i 's/border-gray-800/border-#00ff41\/20/g' "$f"
  # RING
  sed -i 's/ring-green-400\/20/ring-#00ff41\/20/g' "$f"
  sed -i 's/focus:ring-green-500/focus:ring-#00ff41/g' "$f"
  sed -i 's/focus:ring-green-400/focus:ring-#00ff41/g' "$f"
  sed -i 's/focus:ring-emerald-500/focus:ring-#00ff41/g' "$f"
  sed -i 's/focus:border-green-500/focus:border-#00ff41/g' "$f"
  # HOVER
  sed -i 's/hover:bg-green-500/hover:bg-#66ff66/g' "$f"
  sed -i 's/hover:bg-green-600/hover:bg-#66ff66/g' "$f"
  sed -i 's/hover:bg-green-700/hover:bg-#66ff66/g' "$f"
  sed -i 's/hover:bg-green-900\/30/hover:bg-#00ff41\/20/g' "$f"
  sed -i 's/hover:bg-green-800/hover:bg-#00ff41\/20/g' "$f"
  sed -i 's/hover:bg-emerald-600/hover:bg-#66ff66/g' "$f"
  sed -i 's/hover:bg-emerald-700/hover:bg-#66ff66/g' "$f"
  sed -i 's/hover:text-green-300/hover:text-#66ff66/g' "$f"
  sed -i 's/hover:border-green-500\/30/hover:border-#00ff41\/30/g' "$f"
  sed -i 's/hover:border-green-400/hover:border-#66ff66/g' "$f"
  # GRADIENTS
  sed -i 's/from-green-600 to-green-500/from-#00ff41 to-#66ff66/g' "$f"
  sed -i 's/from-green-500 to-green-400/from-#00ff41 to-#66ff66/g' "$f"
  sed -i 's/from-green-400 to-green-500/from-#00ff41 to-#66ff66/g' "$f"
  sed -i 's/from-green-500\/10 to-transparent/from-#00ff41\/10 to-transparent/g' "$f"
  sed -i 's/bg-gradient-to-br from-green-600 to-green-500/bg-#00ff41/g' "$f"
  sed -i 's/bg-gradient-to-r from-green-500 to-green-600/bg-#00ff41/g' "$f"
  # SHADOWS
  sed -i 's/shadow-green-500\/25/shadow-#00ff41\/25/g' "$f"
  sed -i 's/shadow-green-600\/25/shadow-#00ff41\/25/g' "$f"
  sed -i 's/shadow-green-400\/20/shadow-#00ff41\/20/g' "$f"
  sed -i 's/shadow-green-500\/20/shadow-#00ff41\/20/g' "$f"
  sed -i 's/shadow-emerald-500\/25/shadow-#00ff41\/25/g' "$f"
  # PLACEHOLDER / DIVIDE / CARET
  sed -i 's/placeholder-gray-400/placeholder-#00cc33/g' "$f"
  sed -i 's/placeholder-gray-500/placeholder-#00cc33/g' "$f"
  sed -i 's/divide-gray-700\/50/divide-#00ff41\/20/g' "$f"
  sed -i 's/caret-green-500/caret-#00ff41/g' "$f"
done
echo "Easyreadvoice transformation complete!"
